#[derive(Clone, Copy, PartialEq, Eq, Debug)]
pub enum Lang {
    Es,
    En,
    Ru,
}

impl Lang {
    pub fn label(&self) -> &'static str {
        match self {
            Lang::Es => "Español",
            Lang::En => "English",
            Lang::Ru => "Русский",
        }
    }

    pub fn code(&self) -> &'static str {
        match self {
            Lang::Es => "es",
            Lang::En => "en",
            Lang::Ru => "ru",
        }
    }

    pub fn all() -> [Lang; 3] {
        [Lang::Es, Lang::En, Lang::Ru]
    }

    pub fn parse(s: &str) -> Self {
        match s.trim() {
            "en" => Lang::En,
            "ru" => Lang::Ru,
            _ => Lang::Es,
        }
    }
}

